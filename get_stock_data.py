# 市場全体の地合いを見る指数。先頭が "_" のファイルは
# 検証ノート側で「銘柄」ではなく「指数」として扱われます。
INDEXES = {
    "^N225": "_日経平均",
    "^TPX": "_TOPIX",
}

OUT_DIR = "data"     # 保存先フォルダ
BUDGET = 200000      # 使える資金（円）。100株買えるかの判定に使います

# 銘柄をふるいにかける基準
MIN_TURNOVER = 1e8   # 1日の売買代金の下限（円）
MAX_COST_SHARE = 20  # 1ティックが平均値幅に占める割合の上限（％）
MIN_VOL_TREND = 0.6  # 出来高の勢いの下限（直近20日 ÷ その前60日）


# ============================================================
# ここから下は触らなくて大丈夫です
# ============================================================

COLS = ["日付", "始値", "高値", "安値", "終値", "出来高"]


def tick_size(price):
    """東証の呼値（TOPIX100以外の通常銘柄）"""
    if price <= 3000:
        return 1
    if price <= 5000:
        return 5
    if price <= 30000:
        return 10
    if price <= 50000:
        return 50
    return 100


def atr14(df):
    """ATR（1本あたりの平均値幅）をWilder方式で計算する"""
    high, low, close = df["High"], df["Low"], df["Close"]
    prev = close.shift(1)
    tr = pd.concat([high - low, (high - prev).abs(), (low - prev).abs()], axis=1).max(axis=1)
    return tr.ewm(alpha=1 / 14, adjust=False).mean()


def read_existing(path):
    """既存CSVを読む。無ければ None"""
    if not os.path.exists(path):
        return None
    try:
        df = pd.read_csv(path, encoding="utf-8-sig")
        if "日付" not in df.columns or df.empty:
            return None
        df["日付"] = pd.to_datetime(df["日付"], errors="coerce")
        df = df.dropna(subset=["日付"]).sort_values("日付")
        return df if len(df) else None
    except Exception:
        return None


def download(symbol, start=None):
    """start を指定すればその日以降、しなければ取れるだけ全部"""
    kw = dict(interval="1d", progress=False, auto_adjust=False)
    if start is None:
        df = yf.download(symbol, period="max", **kw)
    else:
        df = yf.download(symbol, start=start.strftime("%Y-%m-%d"), **kw)
    if df is None or df.empty:
        return None
    if isinstance(df.columns, pd.MultiIndex):
        df.columns = df.columns.get_level_values(0)
    return df.dropna(subset=["Open", "High", "Low", "Close"])


def to_rows(df):
    """yfinance の形式を、検証ノートが読む形式に直す"""
    idx = df.index
    if getattr(idx, "tz", None) is not None:
        idx = idx.tz_localize(None)
    return pd.DataFrame({
        "日付": idx,
        "始値": df["Open"].round(1).values,
        "高値": df["High"].round(1).values,
        "安値": df["Low"].round(1).values,
        "終値": df["Close"].round(1).values,
        "出来高": (df["Volume"].fillna(0).astype("int64").values
                   if "Volume" in df.columns else 0),
    })


def save(path, df):
    out = df.copy()
    out["日付"] = pd.to_datetime(out["日付"]).dt.strftime("%Y/%m/%d")
    out[COLS].to_csv(path, index=False, encoding="utf-8-sig")


def merge_and_save(path, new_df, old_df):
    """既存と新規を結合。日付が重なった行は新しいほうを残す"""
    if old_df is None:
        merged = new_df.sort_values("日付")
        added = len(merged)
    else:
        before = len(old_df)
        merged = pd.concat([old_df, new_df], ignore_index=True)
        merged = merged.drop_duplicates(subset="日付", keep="last").sort_values("日付")
        added = len(merged) - before
    merged = merged.reset_index(drop=True)
    save(path, merged)
    return merged, added


def fetch_one(code, name, is_index=False):
    """1件ぶん取得して保存し、結果を返す"""
    symbol = code if is_index else f"{code}.T"
    fname = f"{name}.csv" if is_index else f"{code}_{name}.csv"
    path = os.path.join(OUT_DIR, fname)
    old = read_existing(path)

    if old is None:
        df = download(symbol)                                   # 初回は取れるだけ
        mode = "新規"
    else:
        last = old["日付"].max()
        df = download(symbol, start=last - timedelta(days=7))   # 数日重ねて取りこぼしを防ぐ
        mode = "追記"
        if df is None or df.empty:
            return {"rows": len(old), "added": 0, "mode": "変化なし", "df": old, "path": path}

    if df is None or df.empty:
        return None
    merged, added = merge_and_save(path, to_rows(df), old)
    return {"rows": len(merged), "added": added, "mode": mode, "df": merged, "path": path}


def screen(merged):
    """ふるい分けの数値を出す。merged は日付昇順"""
    df = merged.rename(columns={"高値": "High", "安値": "Low",
                                "終値": "Close", "出来高": "Volume"})
    px = float(df["Close"].iloc[-1])
    atr = float(atr14(df).iloc[-1])
    atr_pct = atr / px * 100 if px else 0
    tick = tick_size(px)
    cost_share = (tick / px * 100) / atr_pct * 100 if atr_pct > 0 else 999
    turnover = float((df["Volume"] * df["Close"]).tail(60).median())
    v_recent = float(df["Volume"].tail(20).median())
    v_before = float(df["Volume"].tail(80).head(60).median())
    v_trend = v_recent / v_before if v_before > 0 else 0

    flags = []
    if turnover < MIN_TURNOVER:
        flags.append("売買代金が少ない")
    if cost_share > MAX_COST_SHARE:
        flags.append("呼値が値幅に対して大きい")
    if v_trend < MIN_VOL_TREND:
        flags.append("出来高が細っている")
    if px * 100 > BUDGET:
        flags.append("予算超え")
    return {"px": px, "atr_pct": atr_pct, "turnover": turnover,
            "v_trend": v_trend, "flags": flags}


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    print(f"取得開始  {datetime.now():%Y-%m-%d %H:%M}")
    print("初回は取れるだけ遡り、2回目以降は続きだけを追記します。\n")

    for sym, nm in INDEXES.items():
        print(f"  指数 {nm} ...", end=" ", flush=True)
        try:
            r = fetch_one(sym, nm, is_index=True)
            print(f"{r['mode']} +{r['added']}行 → 計{r['rows']}行" if r else "取得できず")
        except Exception as e:
            print(f"失敗（{type(e).__name__}）")

    results, errors = [], []
    for code, name in TICKERS.items():
        print(f"  {code} {name} ...", end=" ", flush=True)
        try:
            r = fetch_one(code, name)
            if not r or r["rows"] < 120:
                raise ValueError(f"{r['rows'] if r else 0}行しかありません")
            s = screen(r["df"])
            first = pd.to_datetime(r["df"]["日付"]).min().strftime("%Y/%m")
            print(f"{r['mode']} +{r['added']}行 → 計{r['rows']}行（{first}〜）")
            results.append({"code": code, "name": name, "rows": r["rows"],
                            "first": first, **s})
        except Exception as e:
            print(f"失敗（{e}）")
            errors.append((code, name, str(e)))

    if not results:
        print("\n1件も取得できませんでした。")
        return

    results.sort(key=lambda r: (len(r["flags"]), -r["turnover"]))
    ok = [r for r in results if not r["flags"]]
    ng = [r for r in results if r["flags"]]

    print("\n" + "=" * 72)
    print(f"使える銘柄  {len(ok)} / {len(results)} 件   （予算 {BUDGET:,} 円）")
    print("=" * 72)
    if ok:
        print(f"{'コード':<7}{'銘柄':<12}{'株価':>7}{'100株':>9}{'値幅':>7}{'売買代金':>10}{'開始':>10}")
        print("-" * 72)
        for r in ok:
            print(f"{r['code']:<7}{r['name']:<12}{r['px']:>7.0f}{r['px'] * 100:>9,.0f}"
                  f"{r['atr_pct']:>6.2f}%{r['turnover'] / 1e8:>9.2f}億{r['first']:>10}")
    else:
        print("条件を満たす銘柄がありませんでした。")

    if ng:
        counts = {}
        for r in ng:
            for f in r["flags"]:
                counts[f] = counts.get(f, 0) + 1
        print(f"\n除外 {len(ng)} 件の内訳")
        for k, v in sorted(counts.items(), key=lambda x: -x[1]):
            print(f"  {k}: {v} 件")

    oldest = min(r["first"] for r in results)
    shortest = min(r["rows"] for r in results)
    print(f"\n最も古いデータ: {oldest}　最も行数の少ない銘柄: {shortest}行")
    if shortest < 2500:
        print("※ 2500行（約10年）に満たない銘柄があります。新規上場などが原因です。")

    if errors:
        print("\n取得できなかった銘柄:")
        for code, name, e in errors:
            print(f"  {code} {name}: {e[:60]}")

    print(f"\nCSVは {os.path.abspath(OUT_DIR)} に出ています。")
    print("検証ノートの「データ」タブに、中身をまとめてドラッグ&ドロップしてください。")


if __name__ == "__main__":
    main()
